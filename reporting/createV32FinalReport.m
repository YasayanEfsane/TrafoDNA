function report = localWriteReportFiles(report,prepared,finalResult,options)
paths.summaryCsv = fullfile(options.outputDirectory, ...
    'v32_final_report_summary.csv');
paths.scenarioCsv = fullfile(options.outputDirectory, ...
    'v32_final_scenario_metrics.csv');
paths.perBitCsv = fullfile(options.outputDirectory, ...
    'v32_final_per_bit_metrics.csv');
paths.correlationCsv = fullfile(options.outputDirectory, ...
    'v32_reference_bit_correlation.csv');
paths.integrityCsv = fullfile(options.outputDirectory, ...
    'v32_final_integrity.csv');
paths.manifestCsv = fullfile(options.outputDirectory, ...
    'v32_evidence_manifest.csv');
paths.markdown = fullfile(options.outputDirectory,'V32_FINAL_OUTCOME.md');
paths.html = fullfile(options.outputDirectory,'V32_FINAL_REPORT.html');
paths.mat = fullfile(options.outputDirectory,'v32_final_report.mat');

writetable(report.summaryTable,paths.summaryCsv);
writetable(report.scenarioTable,paths.scenarioCsv);
writetable(report.perBitTable,paths.perBitCsv);
bitNames = arrayfun(@(k) sprintf('Bit%02d',k), ...
    1:size(report.referenceBitCorrelation,2),'UniformOutput',false);
correlationTable = array2table(report.referenceBitCorrelation, ...
    'VariableNames',bitNames,'RowNames',bitNames);
writetable(correlationTable,paths.correlationCsv,'WriteRowNames',true);
writetable(report.integrityTable,paths.integrityCsv);
if ~isempty(report.evidenceManifest)
    writetable(report.evidenceManifest,paths.manifestCsv);
end
localWriteMarkdown(paths.markdown,report,prepared,finalResult);
localWriteHtml(paths.html,report,prepared,finalResult);
report.outputFiles = paths;
save(paths.mat,'report','-v7');
end

function localWriteMarkdown(fileName,report,prepared,finalResult)
fileId = localOpenTextFile(fileName);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId,'# TrafoDNA V3.2 Locked Final Outcome\n\n');
fprintf(fileId,'## Decision\n\n');
fprintf(fileId,'**Preregistered numerical hypothesis: %s (%d/10 gates).**\n\n', ...
    report.decision,sum(report.summaryTable.FinalPassed));
fprintf(fileId,['The frozen projected challenge-response representation ' ...
    'was evaluated on a new 64-core virtual population and locked final ' ...
    'scenarios 215--218.\n\n']);
fprintf(fileId,'## Development and locked-final metrics\n\n');
fprintf(fileId,['| Metric | Development | Locked final | Target | ' ...
    'Final result |\n']);
fprintf(fileId,'|---|---:|---:|---|:---:|\n');
for k = 1:height(report.summaryTable)
    outcome = localPassFail(report.summaryTable.FinalPassed(k));
    fprintf(fileId,'| %s | %s | %s | %s | %s |\n', ...
        report.summaryTable.Metric{k}, ...
        localFormatMetric(k,report.summaryTable.Development(k)), ...
        localFormatMetric(k,report.summaryTable.LockedFinal(k)), ...
        report.summaryTable.Target{k},outcome);
end
fprintf(fileId,'\n## Integrity record\n\n');
for k = 1:height(report.integrityTable)
    fprintf(fileId,'- %s: `%s`\n',report.integrityTable.Item{k}, ...
        report.integrityTable.Value{k});
end
fprintf(fileId,'\n## Evidence-file SHA-256\n\n');
if isempty(report.evidenceManifest)
    fprintf(fileId,'No external evidence manifest was supplied.\n');
else
    for k = 1:height(report.evidenceManifest)
        fprintf(fileId,'- `%s`: `%s`\n', ...
            report.evidenceManifest.FileName{k}, ...
            report.evidenceManifest.SHA256{k});
    end
end
fprintf(fileId,'\n## Figures\n\n');
captions = localFigureCaptions();
for k = 1:numel(report.figureFiles)
    [~,base,extension] = fileparts(report.figureFiles{k});
    fprintf(fileId,'![%s](figures/%s%s)\n\n',captions{k},base,extension);
end
fprintf(fileId,'## Interpretation\n\n');
fprintf(fileId,['V3.2 passed all ten frozen gates. Final identity accuracy ' ...
    'was %.2f%% with EER %.4f. The %d-bit projected response achieved ' ...
    'reliability %.4f, uniqueness %.4f, worst-scenario reliability ' ...
    '%.4f, and three-sweep reliability %.4f.\n\n'], ...
    100*finalResult.identityMetrics.accuracy,finalResult.identityMetrics.eer, ...
    finalResult.pufMetrics.numSelectedBits, ...
    finalResult.pufMetrics.reliability,finalResult.pufMetrics.uniqueness, ...
    finalResult.worstConditionPUFReliability, ...
    finalResult.sessionPUFMetrics.reliability);
fprintf(fileId,['This supports numerical feasibility only. It is not ' ...
    'physical transformer validation, proof of independent key entropy, ' ...
    'or cryptographic security validation. Maximum selected-bit reference ' ...
    'correlation was %.4f.\n'], ...
    finalResult.pufModel.maximumSelectedCorrelation);
fprintf(fileId,'\nPreparation final rows used: %d.\n', ...
    prepared.integrity.finalRowsUsed);
clear cleanup
end


function report = createV32FinalReport(preparedV32,finalV32,options)
%CREATEV32FINALREPORT Build a read-only V3.2 evidence report.
%   The function validates the frozen contract and stored metrics, then
%   writes tables, figures, Markdown, and Word-readable HTML. It never fits
%   a model, generates a scenario, or modifies either locked input result.

if nargin < 3 || isempty(options)
    options = struct();
end
options = localOptions(options,preparedV32);
recomputedChecks = localValidateInputs(preparedV32,finalV32);

summaryTable = localSummaryTable(preparedV32,finalV32);
scenarioTable = localScenarioTable(finalV32);
[perBitTable,referenceCorrelation] = localPerBitTable(finalV32);
integrityTable = localIntegrityTable(preparedV32,finalV32);

if finalV32.hypothesisSupported
    decision = 'SUPPORTED';
else
    decision = 'NOT SUPPORTED';
end
report.study = finalV32.study;
report.protocolVersion = finalV32.protocolVersion;
report.status = 'locked_final_report_generated';
report.decision = decision;
report.hypothesisSupported = finalV32.hypothesisSupported;
report.integrityVerified = true;
report.storedChecksReproduced = isequal(recomputedChecks.Passed, ...
    finalV32.checks.Passed);
report.summaryTable = summaryTable;
report.scenarioTable = scenarioTable;
report.perBitTable = perBitTable;
report.referenceBitCorrelation = referenceCorrelation;
report.integrityTable = integrityTable;
report.evidenceManifest = options.evidenceManifest;
report.outputDirectory = options.outputDirectory;
report.figureFiles = cell(0,1);
report.outputFiles = struct();

if options.saveFiles
    localEnsureDirectory(options.outputDirectory);
    localEnsureDirectory(options.figureDirectory);
end
if options.createFigures
    if ~options.saveFiles
        error('TrafoDNA:V32ReportFigureDestinationRequired', ...
            'Figure creation requires saveFiles=true.');
    end
    report.figureFiles = localCreateFigures(preparedV32,finalV32, ...
        scenarioTable,perBitTable,referenceCorrelation,options);
end
if options.saveFiles
    report = localWriteReportFiles(report,preparedV32,finalV32,options);
end
if options.verbose
    localPrintReport(report);
end
end

function options = localOptions(options,prepared)
defaults.outputDirectory = fullfile( ...
    prepared.cfg.runtime.resultsDirectory,'report');
defaults.figureVisible = 'off';
defaults.createFigures = true;
defaults.saveFiles = true;
defaults.verbose = true;
defaults.evidenceManifest = table();
names = fieldnames(defaults);
for k = 1:numel(names)
    if ~isfield(options,names{k})
        options.(names{k}) = defaults.(names{k});
    end
end
options.createFigures = logical(options.createFigures);
options.saveFiles = logical(options.saveFiles);
options.verbose = logical(options.verbose);
options.outputDirectory = char(options.outputDirectory);
options.figureDirectory = fullfile(options.outputDirectory,'figures');
if ~istable(options.evidenceManifest)
    error('TrafoDNA:InvalidV32EvidenceManifest', ...
        'The evidence manifest must be a table.');
end
end

function recomputed = localValidateInputs(prepared,finalResult)
preparedFields = {'cfg','contract','development','pufModel','integrity'};
finalFields = {'study','protocolVersion','status','contract','metadata', ...
    'identityPrediction','identityMetrics','pufMetrics', ...
    'worstConditionPUFReliability','pufByCondition', ...
    'sessionIdentityMetrics','sessionPUFMetrics','pufModel','checks', ...
    'hypothesisSupported','integrity'};
localRequireFields(prepared,preparedFields,'prepared bundle');
localRequireFields(finalResult,finalFields,'locked final result');
if ~strcmp(finalResult.status,'locked_final_observed') || ...
        ~isequaln(prepared.contract,finalResult.contract) || ...
        ~isequaln(prepared.contract, ...
        buildV32ProtocolContract(prepared.cfg))
    error('TrafoDNA:V32ReportContractMismatch', ...
        'Prepared and final protocol contracts do not agree.');
end
if prepared.integrity.finalRowsGenerated ~= 0 || ...
        prepared.integrity.finalRowsUsed ~= 0
    error('TrafoDNA:V32ReportPreparationLeakage', ...
        'Preparation does not preserve a zero-final-row state.');
end
if ~istable(finalResult.metadata) || ...
        numel(finalResult.identityPrediction) ~= height(finalResult.metadata)
    error('TrafoDNA:V32ReportDimensionMismatch', ...
        'Final metadata and predictions have inconsistent dimensions.');
end
rowCount = height(finalResult.metadata);
observedIds = unique(finalResult.metadata.ConditionId,'stable')';
expectedRows = prepared.cfg.dataset.numCores* ...
    numel(prepared.cfg.dataset.finalHoldoutConditionIds)* ...
    prepared.cfg.dataset.repetitions;
if finalResult.integrity.finalRowsGenerated ~= rowCount || ...
        finalResult.integrity.finalRowsUsed ~= rowCount || ...
        finalResult.integrity.preparationFinalRowsUsed ~= 0 || ...
        ~isequal(finalResult.integrity.finalConditionIds,observedIds) || ...
        ~isequal(observedIds, ...
        prepared.cfg.dataset.finalHoldoutConditionIds) || ...
        rowCount ~= expectedRows || ...
        ~all(finalResult.metadata.IsFinalHoldoutCondition) || ...
        any(finalResult.metadata.IsUnseenCondition)
    error('TrafoDNA:V32ReportIntegrityMismatch', ...
        'Stored V3.2 final-row integrity evidence is inconsistent.');
end
if ~istable(finalResult.checks) || height(finalResult.checks) ~= 10 || ...
        ~istable(prepared.development.checks) || ...
        height(prepared.development.checks) ~= 10
    error('TrafoDNA:V32ReportInvalidChecks', ...
        'Both development and final reports require ten checks.');
end
recomputed = evaluateV32Checks(finalResult.identityMetrics, ...
    finalResult.pufMetrics,finalResult.worstConditionPUFReliability, ...
    finalResult.sessionIdentityMetrics,finalResult.sessionPUFMetrics, ...
    finalResult.pufModel,prepared.cfg);
if max(abs(recomputed.Current-finalResult.checks.Current)) > 1e-12 || ...
        ~isequal(recomputed.Passed,finalResult.checks.Passed) || ...
        finalResult.hypothesisSupported ~= all(finalResult.checks.Passed)
    error('TrafoDNA:V32ReportCheckMismatch', ...
        'Stored final checks cannot be reproduced from locked metrics.');
end
if ~isequal(prepared.pufModel.referenceBits, ...
        finalResult.pufModel.referenceBits) || ...
        ~isequal(prepared.pufModel.selectedCandidateIndices, ...
        finalResult.pufModel.selectedCandidateIndices)
    error('TrafoDNA:V32ReportFrozenModelMismatch', ...
        'The final PUF model differs from the prepared frozen model.');
end
end

function localRequireFields(value,fields,label)
for k = 1:numel(fields)
    if ~isfield(value,fields{k})
        error('TrafoDNA:V32ReportMissingField', ...
            '%s is missing field "%s".',label,fields{k});
    end
end
end

function summary = localSummaryTable(prepared,finalResult)
developmentChecks = prepared.development.checks;
finalChecks = finalResult.checks;
if ~isequal(developmentChecks.Metric,finalChecks.Metric)
    error('TrafoDNA:V32ReportMetricOrderChanged', ...
        'Development and final metric names do not match.');
end
summary = table(finalChecks.Metric,developmentChecks.Current, ...
    finalChecks.Current,finalChecks.Target,developmentChecks.Passed, ...
    finalChecks.Passed,'VariableNames',{'Metric','Development', ...
    'LockedFinal','Target','DevelopmentPassed','FinalPassed'});
end

function scenarioTable = localScenarioTable(finalResult)
conditionIds = unique(finalResult.metadata.ConditionId,'stable');
sampleCount = zeros(numel(conditionIds),1);
identityAccuracy = zeros(numel(conditionIds),1);
pufReliability = zeros(numel(conditionIds),1);
for k = 1:numel(conditionIds)
    selected = finalResult.metadata.ConditionId == conditionIds(k);
    sampleCount(k) = sum(selected);
    identityAccuracy(k) = mean(finalResult.identityPrediction(selected) == ...
        finalResult.metadata.CoreId(selected));
    tableRow = finalResult.pufByCondition.ConditionId == conditionIds(k);
    if nnz(tableRow) ~= 1
        error('TrafoDNA:V32ReportMissingScenarioMetric', ...
            'Final PUF reliability is missing for condition %d.', ...
            conditionIds(k));
    end
    pufReliability(k) = finalResult.pufByCondition.Reliability(tableRow);
end
scenarioTable = table(conditionIds,sampleCount,identityAccuracy, ...
    pufReliability,'VariableNames',{'ConditionId','SampleCount', ...
    'IdentityAccuracy','PUFReliability'});
end

function [perBitTable,correlation] = localPerBitTable(finalResult)
bits = logical(finalResult.pufMetrics.testBits);
referenceBits = logical(finalResult.pufModel.referenceBits);
numBits = size(referenceBits,2);
if size(bits,1) ~= height(finalResult.metadata) || ...
        size(bits,2) ~= numBits || numBits < 1
    error('TrafoDNA:V32ReportInvalidBits', ...
        'Final bit responses do not match the frozen reference width.');
end
agreement = false(size(bits));
for row = 1:size(bits,1)
    corePosition = find(finalResult.pufModel.coreIds == ...
        finalResult.metadata.CoreId(row),1);
    if isempty(corePosition)
        error('TrafoDNA:V32ReportUnknownCore', ...
            'A final response does not have an enrolled reference.');
    end
    agreement(row,:) = bits(row,:) == referenceBits(corePosition,:);
end
correlation = corrcoef(double(referenceBits));
correlation(~isfinite(correlation)) = 0;
correlation(1:numBits+1:end) = 1;
offDiagonal = abs(correlation);
offDiagonal(1:numBits+1:end) = 0;

bitNumber = (1:numBits)';
candidateIndex = localSelectedColumn(finalResult.pufModel, ...
    'CandidateIndex',numBits);
enrollmentReliability = localSelectedColumn(finalResult.pufModel, ...
    'EnrollmentReliability',numBits);
validationReliability = localSelectedColumn(finalResult.pufModel, ...
    'ValidationReliability',numBits);
worstKnownReliability = localSelectedColumn(finalResult.pufModel, ...
    'WorstKnownConditionReliability',numBits);
selectionScore = localSelectedColumn(finalResult.pufModel, ...
    'SelectionScore',numBits);
finalReliability = mean(agreement,1)';
referenceOneRate = mean(referenceBits,1)';
finalOneRate = mean(bits,1)';
maximumAbsCorrelation = max(offDiagonal,[],2);
perBitTable = table(bitNumber,candidateIndex,enrollmentReliability, ...
    validationReliability,worstKnownReliability,selectionScore, ...
    finalReliability,referenceOneRate,finalOneRate, ...
    maximumAbsCorrelation,'VariableNames',{'Bit','CandidateIndex', ...
    'EnrollmentReliability','ValidationReliability', ...
    'WorstKnownConditionReliability','SelectionScore', ...
    'FinalReliability','ReferenceOneRate','FinalOneRate', ...
    'MaximumAbsReferenceCorrelation'});
end

function values = localSelectedColumn(model,variableName,count)
values = NaN(count,1);
if isfield(model,'selectedBitsTable') && istable(model.selectedBitsTable) && ...
        height(model.selectedBitsTable) == count && ...
        ismember(variableName,model.selectedBitsTable.Properties.VariableNames)
    values = model.selectedBitsTable.(variableName);
    values = values(:);
end
end

function integrityTable = localIntegrityTable(prepared,finalResult)
if finalResult.hypothesisSupported
    decision = 'SUPPORTED';
else
    decision = 'NOT SUPPORTED';
end
item = {'Protocol version';'Final status';'Decision'; ...
    'Development rows generated';'Preparation final rows generated'; ...
    'Preparation final rows used';'Final rows generated'; ...
    'Final rows used';'Final condition IDs';'Selected projected bits'};
value = {finalResult.protocolVersion;finalResult.status;decision; ...
    sprintf('%d',prepared.integrity.developmentRowsGenerated); ...
    sprintf('%d',prepared.integrity.finalRowsGenerated); ...
    sprintf('%d',prepared.integrity.finalRowsUsed); ...
    sprintf('%d',finalResult.integrity.finalRowsGenerated); ...
    sprintf('%d',finalResult.integrity.finalRowsUsed); ...
    strtrim(sprintf('%d ',finalResult.integrity.finalConditionIds)); ...
    sprintf('%d',finalResult.pufMetrics.numSelectedEligibleBits)};
integrityTable = table(item,value,'VariableNames',{'Item','Value'});
end


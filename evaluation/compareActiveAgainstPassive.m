function comparison = compareActiveAgainstPassive(finalEvaluation,cfg)
%COMPAREACTIVEAGAINSTPASSIVE Compare V3 with the locked V2.2 final record.

metric = {'Single-sweep identity accuracy';'Single-sweep identity EER'; ...
    'Raw PUF reliability';'Three-sweep identity accuracy'; ...
    'Three-sweep identity EER';'Three-sweep PUF reliability'};
passiveV22 = [cfg.benchmark.lockedPassiveFinalIdentityAccuracy; ...
    cfg.benchmark.lockedPassiveFinalEER; ...
    cfg.benchmark.lockedPassiveFinalPUFReliability; ...
    cfg.benchmark.lockedPassiveFinalSessionIdentityAccuracy; ...
    cfg.benchmark.lockedPassiveFinalSessionEER; ...
    cfg.benchmark.lockedPassiveFinalSessionPUFReliability];
activeV3 = [finalEvaluation.identityMetrics.accuracy; ...
    finalEvaluation.identityMetrics.eer; ...
    finalEvaluation.pufMetrics.reliability; ...
    finalEvaluation.sessionIdentityMetrics.accuracy; ...
    finalEvaluation.sessionIdentityMetrics.eer; ...
    finalEvaluation.sessionPUFMetrics.reliability];
delta = activeV3-passiveV22;
comparison = table(metric,passiveV22,activeV3,delta, ...
    'VariableNames',{'Metric','PassiveV22','ActiveV3','Delta'});
end

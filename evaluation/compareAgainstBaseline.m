function benchmark = compareAgainstBaseline(testMetrics, unseenMetrics, ...
    pufMetrics, healthMetrics, cfg)
%COMPAREAGAINSTBASELINE Compare current metrics with V1 and V2 targets.
%   The V1 values are the reproducible baseline reported for the default
%   seed. Target checks are engineering gates, not claimed experimental facts.

baseline = cfg.benchmark.baseline;
targets = cfg.benchmark.targets;
metric = {'Known-condition identity accuracy'; ...
    'Development-holdout identity accuracy'; ...
    'Development-holdout EER'; ...
    'PUF reliability'; ...
    'PUF uniqueness'; ...
    'Selected stable bits'; ...
    'Health classification accuracy'};
baselineValue = [baseline.knownIdentityAccuracy; ...
    baseline.unseenIdentityAccuracy; baseline.unseenEER; ...
    baseline.pufReliability; baseline.pufUniqueness; ...
    baseline.selectedBits; baseline.healthAccuracy];
currentValue = [testMetrics.accuracy; unseenMetrics.accuracy; unseenMetrics.eer; ...
    pufMetrics.reliability; pufMetrics.uniqueness; pufMetrics.numSelectedBits; ...
    healthMetrics.accuracy];
target = {sprintf('>= %.2f',targets.knownIdentityAccuracy); ...
    sprintf('>= %.2f',targets.unseenIdentityAccuracy); ...
    sprintf('<= %.2f',targets.maximumUnseenEER); ...
    sprintf('>= %.2f',targets.pufReliability); ...
    sprintf('%.2f to %.2f',targets.pufUniquenessRange); ...
    sprintf('>= %d',targets.minimumSelectedBits); ...
    sprintf('>= %.2f',targets.healthAccuracy)};
passed = [currentValue(1) >= targets.knownIdentityAccuracy; ...
    currentValue(2) >= targets.unseenIdentityAccuracy; ...
    currentValue(3) <= targets.maximumUnseenEER; ...
    currentValue(4) >= targets.pufReliability; ...
    currentValue(5) >= targets.pufUniquenessRange(1) && ...
        currentValue(5) <= targets.pufUniquenessRange(2); ...
    currentValue(6) >= targets.minimumSelectedBits; ...
    currentValue(7) >= targets.healthAccuracy];
deltaFromV1 = currentValue-baselineValue;

benchmark = table(metric, baselineValue, currentValue, deltaFromV1, target, passed, ...
    'VariableNames', {'Metric','V1Baseline','Current','DeltaFromV1','V2Target','Passed'});
end

function checks = evaluateFinalHoldoutChecks(identityMetrics,pufMetrics, ...
    healthMetrics,sessionIdentityMetrics,sessionPUFMetrics,cfg)
%EVALUATEFINALHOLDOUTCHECKS Apply preregistered gates to final conditions.

targets = cfg.benchmark.finalTargets;
metric = {'Single-read identity accuracy';'Single-read identity EER'; ...
    'Single-read PUF reliability';'Health classification accuracy'; ...
    'Three-read identity accuracy';'Three-read identity EER'; ...
    'Three-read PUF reliability'};
currentValue = [identityMetrics.accuracy;identityMetrics.eer; ...
    pufMetrics.reliability;healthMetrics.accuracy; ...
    sessionIdentityMetrics.accuracy;sessionIdentityMetrics.eer; ...
    sessionPUFMetrics.reliability];
target = {sprintf('>= %.2f',targets.identityAccuracy); ...
    sprintf('<= %.2f',targets.maximumEER); ...
    sprintf('>= %.2f',targets.pufReliability); ...
    sprintf('>= %.2f',targets.healthAccuracy); ...
    sprintf('>= %.2f',targets.sessionIdentityAccuracy); ...
    sprintf('<= %.2f',targets.maximumSessionEER); ...
    sprintf('>= %.2f',targets.sessionPUFReliability)};
passed = [currentValue(1) >= targets.identityAccuracy; ...
    currentValue(2) <= targets.maximumEER; ...
    currentValue(3) >= targets.pufReliability; ...
    currentValue(4) >= targets.healthAccuracy; ...
    currentValue(5) >= targets.sessionIdentityAccuracy; ...
    currentValue(6) <= targets.maximumSessionEER; ...
    currentValue(7) >= targets.sessionPUFReliability];
checks = table(metric,currentValue,target,passed, ...
    'VariableNames',{'Metric','Current','Target','Passed'});
end

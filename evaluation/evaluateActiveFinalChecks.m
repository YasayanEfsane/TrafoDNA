function checks = evaluateActiveFinalChecks(identityMetrics,pufMetrics, ...
    worstConditionPUFReliability,sessionIdentityMetrics,sessionPUFMetrics,cfg)
%EVALUATEACTIVEFINALCHECKS Apply the ten preregistered V3 final gates.

targets = cfg.benchmark.activeTargets;
gainOverPassive = identityMetrics.accuracy- ...
    cfg.benchmark.lockedPassiveFinalIdentityAccuracy;
metric = {'Single-sweep identity accuracy';'Single-sweep identity EER'; ...
    'Raw PUF reliability';'PUF uniqueness'; ...
    'Strictly eligible raw fingerprint bits'; ...
    'Worst-final-scenario PUF reliability'; ...
    'Three-sweep identity accuracy';'Three-sweep identity EER'; ...
    'Three-sweep PUF reliability';'Gain over passive final identity'};
currentValue = [identityMetrics.accuracy;identityMetrics.eer; ...
    pufMetrics.reliability;pufMetrics.uniqueness; ...
    pufMetrics.numSelectedEligibleBits;worstConditionPUFReliability; ...
    sessionIdentityMetrics.accuracy; ...
    sessionIdentityMetrics.eer;sessionPUFMetrics.reliability;gainOverPassive];
target = {sprintf('>= %.2f',targets.identityAccuracy); ...
    sprintf('<= %.2f',targets.maximumEER); ...
    sprintf('>= %.2f',targets.pufReliability); ...
    sprintf('%.2f to %.2f',targets.pufUniquenessRange); ...
    sprintf('>= %d',targets.minimumEligibleBits); ...
    sprintf('>= %.2f',targets.worstConditionPUFReliability); ...
    sprintf('>= %.2f',targets.sessionIdentityAccuracy); ...
    sprintf('<= %.2f',targets.maximumSessionEER); ...
    sprintf('>= %.2f',targets.sessionPUFReliability); ...
    sprintf('>= %.2f',targets.minimumGainOverPassive)};
passed = [currentValue(1) >= targets.identityAccuracy; ...
    currentValue(2) <= targets.maximumEER; ...
    currentValue(3) >= targets.pufReliability; ...
    currentValue(4) >= targets.pufUniquenessRange(1) && ...
        currentValue(4) <= targets.pufUniquenessRange(2); ...
    currentValue(5) >= targets.minimumEligibleBits; ...
    currentValue(6) >= targets.worstConditionPUFReliability; ...
    currentValue(7) >= targets.sessionIdentityAccuracy; ...
    currentValue(8) <= targets.maximumSessionEER; ...
    currentValue(9) >= targets.sessionPUFReliability; ...
    currentValue(10) >= targets.minimumGainOverPassive];
checks = table(metric,currentValue,target,passed, ...
    'VariableNames',{'Metric','Current','Target','Passed'});
end
